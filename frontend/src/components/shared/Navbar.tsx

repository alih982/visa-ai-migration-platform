'use client';

import React, { useState, useEffect } from 'react';
import { Link } from '@/i18n/navigation';
import { useTranslations, useLocale } from 'next-intl';
import LanguageSwitcher from './LanguageSwitcher';
import NotificationPanel from './NotificationPanel';
import { Menu, X, ChevronDown, User, LogOut, LayoutDashboard, Heart, ShoppingCart, Phone, MessageCircle, Bot, Sparkles, Stethoscope, Building2 } from 'lucide-react';
import { useAuthStore } from '@/store/useAuthStore';

export default function Navbar() {
    const t = useTranslations('nav');
    const locale = useLocale();
    const isRTL = locale === 'fa';
    const [isScrolled, setIsScrolled] = useState(false);
    const [isMobileMenuOpen, setIsMobileMenuOpen] = useState(false);
    const [isUserMenuOpen, setIsUserMenuOpen] = useState(false);
    const [isChatMenuOpen, setIsChatMenuOpen] = useState(false);
    const [mounted, setMounted] = useState(false);

    const store = useAuthStore();
    const { user, logout } = store;

    const [isAuthenticated, setIsAuthenticated] = useState(false);
    const [displayRole, setDisplayRole] = useState<string>('patient');

    useEffect(() => {
        setMounted(true);
    }, []);

    useEffect(() => {
        if (store.isAuthenticated && store.user) {
            setIsAuthenticated(true);
            setDisplayRole(store.user.role);
        } else {
            const token = localStorage.getItem('token');
            const role = localStorage.getItem('user_role');
            if (token && role) {
                setIsAuthenticated(true);
                setDisplayRole(role);
            }
        }
    }, [store.isAuthenticated, store.user]);

    useEffect(() => {
        const unsubscribe = useAuthStore.subscribe((state) => {
            setIsAuthenticated(state.isAuthenticated);
            if (state.user) {
                setDisplayRole(state.user.role);
            }
        });
        return () => unsubscribe();
    }, []);

    useEffect(() => {
        const handleScroll = () => {
            setIsScrolled(window.scrollY > 20);
        };
        window.addEventListener('scroll', handleScroll);
        return () => window.removeEventListener('scroll', handleScroll);
    }, []);

    const navLinks = [
        { href: `/${locale}`, label: t('home') },
        { href: `/${locale}/doctors`, label: t('doctors') },
        { href: `/${locale}/pharmacy`, label: isRTL ? 'داروخانه' : 'Pharmacy' },
        { href: `/${locale}/services`, label: t('services') },
        { href: `/${locale}/about`, label: t('about') },
    ];

    const getDashboardLink = () => {
        if (!isAuthenticated) return '/dashboard/patient';
        switch (displayRole) {
            case 'admin': return '/dashboard/admin';
            case 'doctor': return '/dashboard/doctor';
            default: return '/dashboard/patient';
        }
    };

    const handleLogout = () => {
        logout();
        localStorage.removeItem('token');
        localStorage.removeItem('user_role');
        localStorage.removeItem('user');
        window.location.href = `/${locale}`;
    };

    useEffect(() => {
        const handleClickOutside = (e: MouseEvent) => {
            const target = e.target as HTMLElement;
            if (!target.closest('.user-menu')) setIsUserMenuOpen(false);
            if (!target.closest('.chat-menu')) setIsChatMenuOpen(false);
        };
        document.addEventListener('click', handleClickOutside);
        return () => document.removeEventListener('click', handleClickOutside);
    }, []);

    if (!mounted) {
        return (
            <nav className="fixed top-0 left-0 right-0 z-50 bg-white/95 backdrop-blur-xl shadow-lg shadow-gray-200/30 border-b border-gray-100">
                <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8">
                    <div className="flex justify-between h-20 items-center">
                        <Link href="/" className="flex items-center gap-3">
                            <div className="relative w-14 h-14">
                                <div className="absolute inset-0 bg-gradient-to-br from-cyan-400 via-blue-500 to-indigo-600 rounded-2xl rotate-6"></div>
                                <div className="absolute inset-0 bg-gradient-to-br from-sky-400 via-blue-500 to-indigo-600 rounded-2xl rotate-3 opacity-70"></div>
                                <div className="absolute inset-0 flex items-center justify-center">
                                    <Stethoscope className="w-7 h-7 text-white relative z-10" />
                                </div>
                            </div>
                            <span className="font-bold text-2xl text-slate-800 tracking-tight">VisaHub</span>
                        </Link>
                    </div>
                </div>
            </nav>
        );
    }

    return (
        <nav
            className={`fixed top-0 left-0 right-0 z-50 transition-all duration-300 ${
                isScrolled || isMobileMenuOpen
                    ? 'bg-white/98 backdrop-blur-xl shadow-lg shadow-gray-200/50'
                    : 'bg-white/90 backdrop-blur-lg'
            }`}
            dir={isRTL ? 'rtl' : 'ltr'}
        >
            <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8">
                <div className="flex justify-between items-center h-20">
                    {/* Logo Section - Premium Design */}
                    <Link href="/" className="flex items-center gap-3 group">
                        <div className="relative w-14 h-14">
                            {/* Layered gradient effect */}
                            <div className="absolute inset-0 bg-gradient-to-br from-cyan-400 via-blue-500 to-indigo-600 rounded-2xl rotate-6 group-hover:rotate-12 transition-transform duration-500 shadow-lg shadow-cyan-500/20"></div>
                            <div className="absolute inset-0 bg-gradient-to-br from-sky-400 via-blue-500 to-indigo-600 rounded-2xl rotate-3 group-hover:rotate-6 transition-transform duration-500 opacity-70"></div>
                            <div className="absolute inset-0 bg-gradient-to-br from-blue-400 via-cyan-500 to-indigo-500 rounded-2xl opacity-50"></div>
                            {/* Icon */}
                            <div className="absolute inset-0 flex items-center justify-center">
                                <Stethoscope className="w-7 h-7 text-white relative z-10 drop-shadow-md" />
                            </div>
                            {/* Sparkle */}
                            <div className="absolute -top-1 -right-1">
                                <Sparkles className="w-4 h-4 text-amber-300 animate-pulse" />
                            </div>
                        </div>
                        <div className="flex flex-col">
                            <span className="text-xl font-bold text-slate-800 group-hover:text-blue-600 transition-colors tracking-tight">VisaHub</span>
                            <span className="text-[9px] font-medium text-slate-400 uppercase tracking-wider flex items-center gap-1">
                                {isRTL ? 'پلتفرم هوشمند' : 'Smart Platform'}
                                <Sparkles size={10} className="text-amber-400" />
                            </span>
                        </div>
                    </Link>

                    {/* Desktop Navigation */}
                    <div className="hidden lg:flex items-center gap-1">
                        {navLinks.map((link, idx) => (
                            <Link
                                key={idx}
                                href={link.href}
                                className="px-4 py-2 text-sm font-semibold text-slate-600 hover:text-blue-600 hover:bg-blue-50 rounded-xl transition-all duration-200"
                            >
                                {link.label}
                            </Link>
                        ))}
                    </div>

                    {/* Right Side */}
                    <div className="flex items-center gap-3">
                        {/* Notification & Language */}
                        <div className="hidden md:flex items-center gap-2">
                            <NotificationPanel />
                            <div className="w-px h-6 bg-slate-200"></div>
                            <LanguageSwitcher />
                        </div>

                        <div className="md:hidden flex items-center gap-2">
                            <LanguageSwitcher />
                        </div>

                        {/* Chat Dropdown */}
                        <div className="relative chat-menu">
                            <button
                                onClick={(e) => {
                                    e.stopPropagation();
                                    setIsChatMenuOpen(!isChatMenuOpen);
                                }}
                                className="flex items-center gap-2 px-4 py-2.5 text-sm font-semibold text-slate-600 hover:text-blue-600 hover:bg-blue-50 rounded-xl transition-all"
                            >
                                <MessageCircle size={18} />
                                <span className="hidden lg:block">{isRTL ? 'پشتیبانی' : 'Support'}</span>
                                <ChevronDown size={14} className={`transition-transform ${isChatMenuOpen ? 'rotate-180' : ''}`} />
                            </button>

                            {isChatMenuOpen && (
                                <div className={`absolute top-full mt-2 w-72 bg-white rounded-2xl shadow-xl shadow-gray-200/50 border border-gray-100 p-3 z-50 ${isRTL ? 'left-0' : 'right-0'}`}>
                                    <Link
                                        href={`/${locale}/dashboard/ai-chat`}
                                        onClick={() => setIsChatMenuOpen(false)}
                                        className="flex items-center gap-3 p-3 rounded-xl hover:bg-indigo-50 transition-colors"
                                    >
                                        <div className="w-10 h-10 bg-gradient-to-br from-indigo-500 to-purple-600 rounded-xl flex items-center justify-center">
                                            <Bot size={18} className="text-white" />
                                        </div>
                                        <div>
                                            <p className="font-bold text-sm text-slate-800">{isRTL ? 'دستیار هوشمند' : 'AI Assistant'}</p>
                                            <p className="text-xs text-slate-500">{isRTL ? 'پاسخگویی ۲۴/۷' : 'Instant 24/7 Answers'}</p>
                                        </div>
                                    </Link>
                                    <Link
                                        href={`/${locale}/dashboard/messages`}
                                        onClick={() => setIsChatMenuOpen(false)}
                                        className="flex items-center gap-3 p-3 rounded-xl hover:bg-emerald-50 transition-colors"
                                    >
                                        <div className="w-10 h-10 bg-gradient-to-br from-emerald-400 to-teal-500 rounded-xl flex items-center justify-center">
                                            <User size={18} className="text-white" />
                                        </div>
                                        <div>
                                            <p className="font-bold text-sm text-slate-800">{isRTL ? 'مشاوره مهاجرتی' : 'Medical Consult'}</p>
                                            <p className="text-xs text-slate-500">{isRTL ? 'ارتباط با پزشک' : 'Direct Doctor Chat'}</p>
                                        </div>
                                    </Link>
                                    <div className="h-px bg-slate-100 my-2"></div>
                                    <a href="tel:1900" className="flex items-center gap-3 p-3 rounded-xl hover:bg-blue-50 transition-colors">
                                        <div className="w-10 h-10 bg-gradient-to-br from-blue-400 to-cyan-500 rounded-xl flex items-center justify-center">
                                            <Phone size={18} className="text-white" />
                                        </div>
                                        <div>
                                            <p className="font-bold text-sm text-slate-800">{isRTL ? 'تماس اضطراری' : 'Emergency'}</p>
                                            <p className="text-xs font-bold text-blue-500">1900</p>
                                        </div>
                                    </a>
                                </div>
                            )}
                        </div>

                        {/* User Menu - Lighter Blue */}
                        {isAuthenticated ? (
                            <div className="relative user-menu">
                                <button
                                    onClick={(e) => {
                                        e.stopPropagation();
                                        setIsUserMenuOpen(!isUserMenuOpen);
                                    }}
                                    className="flex items-center gap-2 px-3 py-2 bg-gradient-to-r from-blue-50 to-cyan-50 hover:from-blue-100 hover:to-cyan-100 border border-blue-200 rounded-full transition-all"
                                >
                                    <div className="w-9 h-9 bg-gradient-to-br from-blue-500 to-cyan-500 rounded-full flex items-center justify-center text-white text-sm font-bold shadow-md">
                                        {displayRole === 'admin' ? 'A' : displayRole === 'doctor' ? 'D' : 'P'}
                                    </div>
                                    <ChevronDown size={14} className="text-blue-500" />
                                </button>

                                {isUserMenuOpen && (
                                    <div className={`absolute top-full mt-2 w-56 bg-white rounded-2xl shadow-xl shadow-blue-200/30 border border-blue-100 p-2 z-50 ${isRTL ? 'left-0' : 'right-0'}`}>
                                        <Link href={getDashboardLink()} onClick={() => setIsUserMenuOpen(false)} className="flex items-center gap-3 px-4 py-3 hover:bg-blue-50 rounded-xl transition-colors">
                                            <LayoutDashboard size={18} className="text-blue-500" />
                                            <span className="font-semibold text-sm text-slate-700">{isRTL ? 'داشبورد' : 'Dashboard'}</span>
                                        </Link>
                                        <Link href={`/${locale}/dashboard/messages`} onClick={() => setIsUserMenuOpen(false)} className="flex items-center gap-3 px-4 py-3 hover:bg-blue-50 rounded-xl transition-colors">
                                            <MessageCircle size={18} className="text-blue-500" />
                                            <span className="font-semibold text-sm text-slate-700">{isRTL ? 'پیام‌ها' : 'Messages'}</span>
                                        </Link>
                                        {displayRole !== 'admin' && (
                                            <Link href={`/${locale}/pharmacy`} onClick={() => setIsUserMenuOpen(false)} className="flex items-center gap-3 px-4 py-3 hover:bg-blue-50 rounded-xl transition-colors">
                                                <ShoppingCart size={18} className="text-blue-500" />
                                                <span className="font-semibold text-sm text-slate-700">{isRTL ? 'داروخانه' : 'Pharmacy'}</span>
                                            </Link>
                                        )}
                                        <div className="h-px bg-slate-100 my-2"></div>
                                        <button onClick={handleLogout} className="flex items-center gap-3 w-full px-4 py-3 text-red-500 hover:bg-red-50 rounded-xl transition-colors">
                                            <LogOut size={18} />
                                            <span className="font-semibold text-sm">{isRTL ? 'خروج' : 'Logout'}</span>
                                        </button>
                                    </div>
                                )}
                            </div>
                        ) : (
                            <div className="hidden sm:flex items-center gap-3">
                                <Link href={`/${locale}/login`} className="px-4 py-2 text-sm font-semibold text-slate-600 hover:text-blue-600 transition-colors">
                                    {t('login')}
                                </Link>
                                <Link href={`/${locale}/signup`} className="px-5 py-2.5 text-sm font-semibold text-white bg-gradient-to-r from-blue-500 via-cyan-500 to-indigo-500 hover:from-blue-600 hover:via-cyan-600 hover:to-indigo-600 rounded-xl shadow-lg shadow-blue-500/25 transition-all">
                                    {t('signup')}
                                </Link>
                            </div>
                        )}

                        {/* Mobile Menu Button */}
                        <button onClick={() => setIsMobileMenuOpen(!isMobileMenuOpen)} className="lg:hidden p-2 hover:bg-slate-100 rounded-xl">
                            {isMobileMenuOpen ? <X size={20} /> : <Menu size={20} />}
                        </button>
                    </div>
                </div>

                {/* Mobile Menu */}
                {isMobileMenuOpen && (
                    <div className="lg:hidden absolute top-full left-0 right-0 bg-white shadow-xl shadow-gray-200/50 border-t border-gray-100 p-4 z-50">
                        <div className="space-y-1">
                            {navLinks.map((link, idx) => (
                                <Link key={idx} href={link.href} onClick={() => setIsMobileMenuOpen(false)} className="block px-4 py-3 text-base font-semibold text-slate-700 hover:text-blue-600 hover:bg-blue-50 rounded-xl">
                                    {link.label}
                                </Link>
                            ))}
                            <div className="h-px bg-slate-100 my-3"></div>
                            <Link href={`/${locale}/dashboard/ai-chat`} onClick={() => setIsMobileMenuOpen(false)} className="flex items-center gap-3 px-4 py-3 text-slate-700 hover:bg-indigo-50 rounded-xl">
                                <Bot size={20} className="text-indigo-500" />
                                <span className="font-semibold">{isRTL ? 'هوش مصنوعی' : 'AI Assistant'}</span>
                            </Link>
                            {isAuthenticated ? (
                                <>
                                    <Link href={getDashboardLink()} onClick={() => setIsMobileMenuOpen(false)} className="flex items-center gap-3 px-4 py-3 text-slate-700 hover:bg-blue-50 rounded-xl">
                                        <LayoutDashboard size={20} className="text-blue-500" />
                                        <span className="font-semibold">{isRTL ? 'داشبورد' : 'Dashboard'}</span>
                                    </Link>
                                    <button onClick={handleLogout} className="flex items-center gap-3 w-full px-4 py-3 text-red-500 hover:bg-red-50 rounded-xl">
                                        <LogOut size={20} />
                                        <span className="font-semibold">{isRTL ? 'خروج' : 'Logout'}</span>
                                    </button>
                                </>
                            ) : (
                                <div className="grid grid-cols-2 gap-3 pt-3">
                                    <Link href={`/${locale}/login`} className="px-4 py-3 text-center font-semibold text-slate-700 bg-slate-100 rounded-xl">{t('login')}</Link>
                                    <Link href={`/${locale}/signup`} class="px-4 py-3 text-center font-semibold text-white bg-blue-500 rounded-xl">{t('signup')}</Link>
                                </div>
                            )}
                        </div>
                    </div>
                )}
            </div>
        </nav>
    );
}

